  // 爻位分析（高岛断法所重：当位、得中、应、比）
  function yaoWei(lines, pos) {
    var yang = lines[pos - 1] === 1;
    var yangPos = (pos % 2 === 1);
    var dangwei = (yang === yangPos);
    var zhong = (pos === 2 || pos === 5);
    var yingPos = pos <= 3 ? pos + 3 : pos - 3;
    var yingYang = lines[yingPos - 1] === 1;
    var youYing = (yingYang !== yang);
    var jinYang = (pos > 1) ? lines[pos - 2] === 1 : null;
    var shangYang = (pos < 6) ? lines[pos] === 1 : null;
    var bi = '';
    if (jinYang !== null && jinYang !== yang) bi += '下邻阴阳相得，为「比」之亲；';
    if (shangYang !== null && shangYang !== yang) bi += '上邻阴阳相得，为「比」之亲；';
    if (jinYang !== null && jinYang === yang) bi += '下邻同气，嫌其相敌；';
    var chengCheng = '';
    if (jinYang !== null && !yang && jinYang) chengCheng = '以阴承阳，顺而得力（承）。';
    else if (jinYang !== null && yang && !jinYang) chengCheng = '以阳乘阴，刚而凌下（乘）。';
    else if (shangYang !== null && !yang && shangYang) chengCheng = '上为阳所乘，受制而难舒（乘）。';

    var POSN = ['初', '二', '三', '四', '五', '上'];
    var parts = [];
    parts.push(yang ? '阳爻' : '阴爻');
    parts.push('居' + POSN[pos - 1] + '位（' + (yangPos ? '阳位' : '阴位') + '）' + (dangwei ? '，当位得正' : '，不当位'));
    parts.push(zhong ? (pos === 5 ? '，得上卦之中，为全卦主位' : '，得下卦之中') : '');
    parts.push(youYing ? '，与' + yingPos + '爻阴阳相应，得外助' : '，与' + yingPos + '爻同为' + (yang ? '阳' : '阴') + '，无应');
    return {
      pos: pos, yang: yang, dangwei: dangwei, zhong: zhong, youYing: youYing,
      text: (parts.join('') + '。' + (bi ? bi : '') + (chengCheng ? chengCheng : '')).replace(/；$/, '。').replace(/，。$/, '。'),
      tip: POS_TIP[pos][1],
      title: POS_TIP[pos][0],
      sanCai: pos <= 2 ? '地' : pos <= 4 ? '人' : '天',
      tone: judgeTone(dangwei, zhong, youYing, pos)
    };
  }

  function judgeTone(dangwei, zhong, youYing, pos) {
    var s = 0;
    if (dangwei) s += 1; else s -= 1;
    if (zhong) s += 1.5;
    if (youYing) s += 1;
    if (pos === 3 || pos === 4) s -= 0.5;
    if (pos === 6) s -= 0.5;
    if (s >= 1.6) return '吉';
    if (s >= 0.4) return '偏吉';
    if (s >= -0.4) return '平';
    if (s >= -1.4) return '偏凶';
    return '凶';
  }

  // 综合：卦断 + 爻位 + 消息卦
  function analyze(name, lines, movings) {
    var t = TAKA[name] || ['', '', ''];
    var res = {
      xiang: t[0], shi: t[1], ji: t[2],
      xiaoxi: XIAOXI[name] || null,
      zeng: ZENG[name] || null,
      wei: []
    };
    if (movings && movings.length) {
      res.wei = movings.map(function (p) { return yaoWei(lines, p); });
    }
    return res;
  }

