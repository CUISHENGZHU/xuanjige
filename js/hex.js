  // 由上下卦名取卦名
  function guaName(upper, lower) { return GRID[upper][TRI_ORDER.indexOf(lower)]; }

  // 由六爻（初爻在前）取卦
  function fromLines(lines) {
    var lob = 0, upb = 0;
    for (var i = 0; i < 3; i++) if (lines[i]) lob += (1 << (2 - i));
    for (var j = 3; j < 6; j++) if (lines[j]) upb += (1 << (5 - j));
    return { lower: BITS_TRI[lob], upper: BITS_TRI[upb], name: guaName(BITS_TRI[upb], BITS_TRI[lob]) };
  }

  // 由卦名取六爻
  function toLines(name) {
    for (var u = 0; u < 8; u++) for (var l = 0; l < 8; l++) {
      if (GRID[TRI_ORDER[u]][l] === name) {
        var up = TRI_BITS[TRI_ORDER[u]], lo = TRI_BITS[TRI_ORDER[l]];
        var bits = [];
        for (var i = 0; i < 3; i++) bits.push((lo >> (2 - i)) & 1);
        for (var j = 0; j < 3; j++) bits.push((up >> (2 - j)) & 1);
        return bits;
      }
    }
    return null;
  }

  // 八宫归属、世应、纳甲、六亲
  var PALACE_CACHE = null;
  function buildPalaces() {
    if (PALACE_CACHE) return PALACE_CACHE;
    var map = {};
    PALACE_NAMES.forEach(function (p) {
      var up = TRI_BITS[p], lo = TRI_BITS[p];
      var step = [
        { lb: lo, ub: up, shi: 6, gen: '本宫' },
        { lb: lo ^ 4, ub: up, shi: 1, gen: '一世' },
        { lb: lo ^ 6, ub: up, shi: 2, gen: '二世' },
        { lb: lo ^ 7, ub: up, shi: 3, gen: '三世' },
        { lb: lo ^ 7, ub: up ^ 4, shi: 4, gen: '四世' },
        { lb: lo ^ 7, ub: up ^ 6, shi: 5, gen: '五世' },
        { lb: lo ^ 7, ub: up ^ 2, shi: 4, gen: '游魂' },
        { lb: lo, ub: up ^ 2, shi: 3, gen: '归魂' }
      ];
      step.forEach(function (s) {
        var nm = guaName(BITS_TRI[s.ub], BITS_TRI[s.lb]);
        map[nm] = { palace: p, wx: PALACE_WX[p], shi: s.shi, ying: s.shi > 3 ? s.shi - 3 : s.shi + 3, gen: s.gen };
      });
    });
    PALACE_CACHE = map;
    return map;
  }

  // 六爻装卦：返回 [{pos,zhi,gan,wx,liuqin,shi,ying}]
  function najia(name) {
    var lines = toLines(name);
    var lower = fromLines(lines).lower, upper = fromLines(lines).upper;
    var pal = buildPalaces()[name];
    var me = pal.wx;
    var out = [];
    for (var i = 0; i < 6; i++) {
      var isLower = i < 3;
      var tri = isLower ? lower : upper;
      var nj = NAJIA[tri];
      var zhi = nj.zhi[isLower ? 0 : 1][i % 3];
      var gan = nj.gan[isLower ? 0 : 1];
      out.push({
        pos: i + 1, gan: gan, zhi: zhi, wx: ZHI_WX[zhi],
        liuqin: liuqin(me, ZHI_WX[zhi]),
        shi: pal.shi === i + 1, ying: pal.ying === i + 1
      });
    }
    return { lines: lines, palace: pal.palace, wx: me, gen: pal.gen, shi: pal.shi, ying: pal.ying, yao: out, upper: upper, lower: lower };
  }

  function liuqin(me, other) {
    var r = relWX(me, other); // 以我（宫五行）为主
    if (r === '比和') return '兄弟';
    if (r === '生') return '子孙';   // 我生者
    if (r === '被生') return '父母';  // 生我者
    if (r === '克') return '妻财';   // 我克者
    if (r === '被克') return '官鬼';  // 克我者
    return '?';
  }

